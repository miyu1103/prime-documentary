"""Regenerate the live-state section of `docs/HANDOVER.md` from the machine, not from memory.

A handover written in prose is accurate for about an hour. The render that was "starting in 35
minutes" has finished, the i2v chain that had "22 clips left" is done, the disk that had 60 GB has
40. A session that reads stale prose and acts on it makes exactly the class of mistake this project
keeps making: acting on a number nobody re-measured.

So `docs/HANDOVER.md` is split in two. Everything between the LIVE-STATE markers is generated by
this command and may be regenerated at any time. Everything outside them is the narrative -- the
judgement, the traps, the reasons -- which only a human or an agent that lived through it can write.

Run this:
  * before ending a session, so the next one inherits measured truth
  * at the start of a session, to see what actually changed while nobody was watching
  * any time the prose and the machine seem to disagree -- the machine wins

  py -3.11 scripts/handover_snapshot.py            # rewrite the block
  py -3.11 scripts/handover_snapshot.py --print    # show it without writing
"""
from __future__ import annotations

import argparse
import json
import re
import shutil
import subprocess
import sys
import tempfile
from datetime import datetime
from pathlib import Path

sys.stdout.reconfigure(encoding="utf-8")
ROOT = Path(__file__).resolve().parent.parent
HANDOVER = ROOT / "docs" / "HANDOVER.md"
BEGIN, END = "<!-- LIVE-STATE:BEGIN -->", "<!-- LIVE-STATE:END -->"

# slug, composition, episode number -- kept in step with queue_unattended.sh JOBS
JOBS = [("marmet", "Ep65Marmet", "65"), ("greene", "Ep62Greene", "62"),
        ("correa", "Ep63Correa", "63"), ("openfields", "Ep66Openfields", "66"),
        ("ramirez", "Ep67Ramirez", "67"), ("pinto", "Ep68Pinto", "68"),
        ("hyatt", "Ep69Hyatt", "69")]


def ps(cmd: str, timeout: int = 90) -> str:
    try:
        r = subprocess.run(["powershell", "-NoProfile", "-Command", cmd], capture_output=True,
                           text=True, encoding="utf-8", errors="replace", timeout=timeout)
        return (r.stdout or "").strip()
    except Exception as exc:
        return f"(could not measure: {exc})"


def procs() -> list[str]:
    """Long-running work, with age. Reported per process so a duplicate is visible, not summarised
    away -- two queue instances raced on 2026-08-11 and a count of '2' looked normal."""
    out = ps(
        "Get-CimInstance Win32_Process | Where-Object { ("
        "$_.CommandLine -like '*queue_unattended*' -or $_.CommandLine -like '*_finish_episode*' -or "
        "$_.CommandLine -like '*_chain_i2v*' -or $_.CommandLine -like '*ComfyUI*' -or "
        "($_.CommandLine -like '*remotion*render*' -and $_.CommandLine -notlike '*--help*')"
        ") -and $_.CommandLine -notlike '*Win32_Process*' -and $_.CommandLine -notlike '*shell-snapshots*' } | "
        "ForEach-Object { $k = if ($_.CommandLine -like '*queue_unattended*') {'queue'} "
        "elseif ($_.CommandLine -like '*_chain_i2v*') {'i2v'} "
        "elseif ($_.CommandLine -like '*_finish_episode*') {'finisher'} "
        "elseif ($_.CommandLine -like '*ComfyUI*') {'comfyui'} else {'render'}; "
        "'{0}|{1}|{2:N0}' -f $k, $_.ProcessId, ((Get-Date)-$_.CreationDate).TotalMinutes }")
    rows = [l for l in out.splitlines() if "|" in l]
    if not rows:
        return ["  nothing running -- no queue, no render, no i2v. THE MACHINE IS IDLE."]
    agg: dict[str, list[str]] = {}
    for l in rows:
        k, pid, age = l.split("|")
        agg.setdefault(k, []).append(f"pid {pid} ({age} min)")
    lines = []
    for k in ("render", "finisher", "i2v", "comfyui", "queue"):
        if k in agg:
            lines.append(f"  {k:9s} {len(agg[k])} process(es): {', '.join(agg[k][:6])}")
    if "queue" not in agg:
        lines.append("  queue     NONE RUNNING -- nothing will start the next episode")
    return lines


def snapshots() -> list[str]:
    snaps = sorted(Path(tempfile.gettempdir()).glob("pdq.*"))
    if not snaps:
        return ["  no queue snapshot -- the queue is not running"]
    out = []
    for s in snaps:
        f = s / "_finish_episode.sh"
        if f.is_file():
            t = f.read_text(encoding="utf-8", errors="replace")
            out.append(f"  {s.name}  4-layer-mux={'yes' if 'build_case_film_mux' in t else 'NO (stale)'}"
                       f"  spec-guard-fixed={'yes' if 'LOG}.satisfied' in t else 'NO (stale)'}"
                       f"  srt-from-filmconfig={'yes' if chr(39)+'captions'+chr(39) in t else 'NO (stale)'}")
        else:
            out.append(f"  {s.name}  (no finisher inside)")
    if len(snaps) > 1:
        out.append("  MORE THAN ONE SNAPSHOT -- two queues are racing the GPU. Kill all, restart one.")
    return out


def episodes() -> list[str]:
    out = [f"  {'slug':11s} {'img':>5s} {'factory':>8s} {'motion':>7s}  {'film.json':>10s}  master"]
    for slug, _comp, num in JOBS:
        pub = ROOT / "remotion" / "public" / slug
        n = lambda d, ext: len(list((pub / d).glob(ext))) if (pub / d).is_dir() else 0
        film = ROOT / "remotion" / "src" / "data" / f"{slug}_film.json"
        eps = sorted(ROOT.glob(f"episodes/PD-*-0{num}-{slug}"))
        master = (eps[0] / f"08_edit/{slug}_final_bgm.v001.mp4") if eps else None
        fm = datetime.fromtimestamp(film.stat().st_mtime).strftime("%m-%d %H:%M") if film.is_file() else "MISSING"
        if master and master.is_file():
            mm = datetime.fromtimestamp(master.stat().st_mtime).strftime("%m-%d %H:%M")
            if film.is_file() and film.stat().st_mtime < master.stat().st_mtime:
                mm += "  <-- QUEUE SKIPS THIS (film older than master)"
        else:
            mm = "none"
        out.append(f"  {slug:11s} {n('img','*.png'):5d} {n('factory','*.mp4'):8d} {n('motion','*.mp4'):7d}  {fm:>10s}  {mm}")
    return out


def disk() -> list[str]:
    out = []
    for label, p in (("repo (C:)", ROOT), ("scratch", Path(tempfile.gettempdir()))):
        try:
            free = shutil.disk_usage(str(p)).free / 1024**3
            flag = "  <-- TOO LOW: renders need ~30 GB" if (label.startswith("repo") and free < 30) else ""
            out.append(f"  {label:10s} {free:7.1f} GB free{flag}")
        except Exception as exc:
            out.append(f"  {label:10s} (could not measure: {exc})")
    for d in ("H:/pd-media",):
        try:
            out.append(f"  {d:10s} {shutil.disk_usage(d).free / 1024**3:7.1f} GB free")
        except Exception:
            pass
    return out


def costs() -> list[str]:
    out = []
    led = ROOT / "runs" / "logs" / "elevenlabs_cost_ledger.tsv"
    if led.is_file():
        rows = [l.split("\t") for l in led.read_text(encoding="utf-8").splitlines()[1:] if l.strip()]
        tot = sum(float(r[3]) for r in rows if len(r) > 3 and r[3].replace(".", "", 1).isdigit())
        out.append(f"  ElevenLabs ledger: {len(rows)} entr(ies), ${tot:.2f} recorded")
    else:
        out.append("  ElevenLabs ledger: not present")
    try:
        r = subprocess.run(["py", "-3.11", str(ROOT / "scripts" / "yt_quota.py")], capture_output=True,
                           text=True, encoding="utf-8", errors="replace", cwd=ROOT, timeout=60)
        first = next((l for l in r.stdout.splitlines() if "spent" in l), "").strip()
        out.append(f"  YouTube quota: {first or '(no reading)'}")
    except Exception as exc:
        out.append(f"  YouTube quota: (could not measure: {exc})")
    return out


def git_state() -> list[str]:
    def g(*a: str) -> str:
        try:
            return subprocess.run(["git", *a], capture_output=True, text=True, encoding="utf-8",
                                  errors="replace", cwd=ROOT, timeout=120).stdout.strip()
        except Exception as exc:
            return f"(could not measure: {exc})"
    dirty = len([l for l in g("status", "--porcelain").splitlines() if l.strip()])
    return [f"  branch {g('rev-parse','--abbrev-ref','HEAD')}  head {g('log','--oneline','-1')}",
            f"  {dirty} uncommitted path(s) -- never `git add -A`: runs/ and SSD media must not be committed"]


def stall() -> list[str]:
    try:
        r = subprocess.run(["py", "-3.11", str(ROOT / "scripts" / "check_queue_will_stall.py")],
                           capture_output=True, text=True, encoding="utf-8", errors="replace",
                           cwd=ROOT, timeout=600)
        return ["  " + l for l in r.stdout.splitlines() if l.strip()] or ["  (no output)"]
    except Exception as exc:
        return [f"  (could not run: {exc})"]


def build() -> str:
    now = datetime.now().strftime("%Y-%m-%d %H:%M")
    p: list[str] = [BEGIN, "",
                    f"## LIVE STATE — measured {now}",
                    "",
                    "Generated by `py -3.11 scripts/handover_snapshot.py`. Everything in this section is a",
                    "measurement, not a recollection. If it disagrees with the narrative below, believe this.",
                    "", "### Running now", ""]
    p += ["```"] + procs() + ["```", "", "### Queue snapshots", "",
          "The queue copies `_finish_episode.sh` at startup and runs the copy for its whole life, so a",
          "queue started before a fix silently keeps the old behaviour.", "", "```"] + snapshots() + ["```", ""]
    p += ["### Episodes", "", "```"] + episodes() + ["```", ""]
    p += ["### Disk", "", "```"] + disk() + ["```", ""]
    p += ["### Spend", "", "```"] + costs() + ["```", ""]
    p += ["### Git", "", "```"] + git_state() + ["```", ""]
    p += ["### Will the queue stall?", "", "```"] + stall() + ["```", "", END]
    return "\n".join(p)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--print", dest="only_print", action="store_true")
    args = ap.parse_args()
    block = build()
    if args.only_print:
        print(block)
        return 0
    if not HANDOVER.is_file():
        raise SystemExit(f"{HANDOVER} does not exist -- create it with the two markers first")
    text = HANDOVER.read_text(encoding="utf-8")
    if BEGIN not in text or END not in text:
        raise SystemExit(f"{HANDOVER} is missing the {BEGIN} / {END} markers")
    new = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END), lambda _m: block, text, flags=re.S)
    HANDOVER.write_text(new, encoding="utf-8")
    print(f"rewrote the live-state block in {HANDOVER}")
    print("\n".join(block.splitlines()[:6]))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
