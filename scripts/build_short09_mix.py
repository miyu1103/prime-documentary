#!/usr/bin/env python3
"""Build SHORT #9 audio mix + caption timing from the English narration index.

Reads short09_narration_index.v002.en_us.json (per-line spoken windows), then:
  - splits each line into readable caption phrases, timed proportionally -> short09_timing.ts
  - mixes narration + BGM (explainer bed) + tension lift + ambience + SFX with sidechain ducking
    and -14 LUFS loudnorm -> final_mix -> copied to remotion/public/shorts/short09/audio/
Bed/tension/ambience bases kept high enough that the 2.70s inter-line gaps don't sag.
All music/SFX are from the rights-tracked library (H:\\pd-media\\library).
"""
from __future__ import annotations

import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
EP = "PD-2026-009-timbs"
MEDIA = Path(json.loads((ROOT / "config/storage.local.json").read_text("utf-8"))["roots"]["media"]["path"])
INDEX = ROOT / "episodes" / EP / "06_audio" / "short09_narration_index.v002.en_us.json"
LIB = MEDIA / "library"
OUT_AUDIO = MEDIA / "episodes" / EP / "07_audio"
REM_PUBLIC = ROOT / "remotion" / "public" / "shorts" / "short09" / "audio"
REM_DATA = ROOT / "remotion" / "src" / "data"
TAIL = 1.0
MIN_CAP = 0.7


def run(cmd: list[str]) -> None:
    subprocess.run(cmd, check=True, capture_output=True)


def dur(path: Path) -> float:
    r = subprocess.run(["ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", str(path)],
                       capture_output=True, text=True)
    return float(r.stdout.strip() or 0)


def split_caption_segments(text: str) -> list[str]:
    """Split a known VO line into readable caption phrases; no Whisper needed."""
    raw = re.split(r"(?<=[。、.!?])\s*", text)
    segs = [s.strip() for s in raw if s.strip()]
    merged: list[str] = []
    for s in segs:
        if merged and (len(s.rstrip("。、")) <= 5 or len(merged[-1]) <= 6):
            merged[-1] = merged[-1] + s
        else:
            merged.append(s)
    return merged or [text]


def build_captions(lines: list[dict]) -> list[dict]:
    caps: list[dict] = []
    for ln in lines:
        segs = split_caption_segments(ln["text"])
        span = max(0.1, ln["end"] - ln["start"])
        weights = [max(1, len(s)) for s in segs]
        wsum = sum(weights)
        cursor = ln["start"]
        for s, w in zip(segs, weights):
            d = max(MIN_CAP, span * w / wsum)
            caps.append({"word": s.rstrip("、"), "startSec": round(cursor, 3), "endSec": round(cursor + d, 3)})
            cursor += d
        if caps:
            caps[-1]["endSec"] = round(ln["end"], 3)
    for i in range(1, len(caps)):
        if caps[i]["startSec"] < caps[i - 1]["endSec"]:
            caps[i]["startSec"] = caps[i - 1]["endSec"]
        if caps[i]["endSec"] <= caps[i]["startSec"]:
            caps[i]["endSec"] = round(caps[i]["startSec"] + MIN_CAP, 3)
    return caps


def write_timing(lines: list[dict], caps: list[dict], total: float) -> None:
    windows = [{"id": ln["id"], "start": round(ln["start"], 3), "end": round(ln["end"], 3)} for ln in lines]
    out = REM_DATA / "short09_timing.ts"
    text = "// AUTO-GENERATED by scripts/build_short09_mix.py — narration-driven timing for SHORT #9.\n"
    text += "import type {ShortCaption} from '../compositions/Short';\n\n"
    text += "export type LineWindow = {id: string; start: number; end: number};\n\n"
    text += f"export const SHORT09_TOTAL_SEC = {round(total, 3)};\n\n"
    text += "export const LINE_WINDOWS: LineWindow[] = " + json.dumps(windows, ensure_ascii=False, indent=2) + ";\n\n"
    text += "export const SHORT09_CAPTIONS: ShortCaption[] = " + json.dumps(caps, ensure_ascii=False, indent=2) + ";\n"
    out.write_text(text, "utf-8")
    print(f"timing -> {out.relative_to(ROOT)}  (lines={len(windows)} captions={len(caps)})")


def build_mix(narration: Path, total: float, lines: list[dict]) -> Path:
    OUT_AUDIO.mkdir(parents=True, exist_ok=True)
    bed = LIB / "music" / "explainer_bed" / "mus_20260614_explainer_bed_soft_explainer_v1.mp3"
    tension = LIB / "music" / "tension_build" / "mus_20260614_tension_build_courtroom_horizon_v1.mp3"
    amb = LIB / "ambience" / "amb_night_window.mp3"
    climax = next((ln["start"] for ln in lines if ln["id"] == "L4"), total - 12)
    cta = next((ln["start"] for ln in lines if ln["id"] == "L5"), total - 4)
    # (file, start_sec_in_video, gain) — aligned to this short's English windows.
    sfx = [
        (LIB / "sfx" / "sfx_riser_2s.mp3", 0.2, 0.34),                 # hook
        (LIB / "sfx" / "sfx_page_turn.mp3", lines[1]["start"] + 0.2, 0.24),  # L2 insurance/SUV
        (LIB / "sfx" / "sfx_sub_drop.mp3", climax + 0.0, 0.30),        # climax / 9-0
        (LIB / "sfx" / "sfx_low_boom.mp3", climax + 0.1, 0.22),
        (LIB / "sfx" / "sfx_stamp_seal.mp3", climax + 4.5, 0.40),      # ruling / got car back
        (LIB / "sfx" / "sfx_whoosh_short.mp3", cta + 0.1, 0.26),       # CTA
    ]
    inputs = ["-i", str(narration),
              "-stream_loop", "-1", "-i", str(bed),
              "-stream_loop", "-1", "-i", str(tension),
              "-stream_loop", "-1", "-i", str(amb)]
    for path, _, _ in sfx:
        inputs += ["-i", str(path)]
    filters = [
        f"[1:a]volume=0.22,atrim=0:{total},asetpts=PTS-STARTPTS[bed0]",
        f"[2:a]volume=0.10,atrim=0:{total},asetpts=PTS-STARTPTS[ten0]",
        f"[3:a]volume=0.05,atrim=0:{total},asetpts=PTS-STARTPTS[amb0]",
        "[bed0][0:a]sidechaincompress=threshold=0.02:ratio=7:attack=40:release=450[bedd]",
        "[ten0][0:a]sidechaincompress=threshold=0.02:ratio=6:attack=40:release=500[tend]",
        "[amb0][0:a]sidechaincompress=threshold=0.015:ratio=9:attack=50:release=600[ambd]",
    ]
    labels = ["[0:a]", "[bedd]", "[tend]", "[ambd]"]
    for idx, (_, delay, vol) in enumerate(sfx, start=4):
        ms = int(delay * 1000)
        filters.append(f"[{idx}:a]volume={vol},adelay={ms}|{ms}[sfx{idx}]")
        labels.append(f"[sfx{idx}]")
    filters.append("".join(labels) + f"amix=inputs={len(labels)}:duration=longest:normalize=0,loudnorm=I=-14:TP=-1:LRA=11[mix]")
    out = OUT_AUDIO / "short09_final_mix_v002_en_us.mp3"
    run(["ffmpeg", "-y", *inputs, "-filter_complex", ";".join(filters),
         "-map", "[mix]", "-t", str(total), "-c:a", "libmp3lame", "-b:a", "192k", str(out)])
    REM_PUBLIC.mkdir(parents=True, exist_ok=True)
    (REM_PUBLIC / out.name).write_bytes(out.read_bytes())
    return out


def main() -> int:
    try:
        sys.stdout.reconfigure(encoding="utf-8")
    except Exception:
        pass
    idx = json.loads(INDEX.read_text("utf-8"))
    lines = idx["lines"]
    narration = Path(idx["master"])
    voice_end = max(ln["end"] for ln in lines)
    total = round(voice_end + TAIL, 3)
    caps = build_captions(lines)
    write_timing(lines, caps, total)
    mix = build_mix(narration, total, lines)
    print(f"narration={narration.name} voice_end={voice_end:.2f}s total={total:.2f}s")
    print(f"mix -> {mix}  ({dur(mix):.2f}s)  + copied to {REM_PUBLIC.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
