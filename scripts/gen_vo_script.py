#!/usr/bin/env python3
"""Write episodes/<EPID>/03_script/script.en.v001.md in [VO:] form, from the authored script.

2026-08-17. build_case_film_audio.py places its SFX and ambience against the narration beats, and
it reads them from `03_script/script.en.v001.md` in `[VO:] one line per beat` form. EP67 ramirez
and EP69 hyatt never had that file, so the sound step died with "script not found" -- which
_finish_episode.sh reports as "the 4-layer mix would fail its density gate", because it treats
any non-zero exit as a density failure. Two episodes were blocked for four hours by a missing
file and a misleading message.

The beats come from `gen_narration_case.build_chunks` -- the SAME extractor that produced the
narration that was actually spoken. Deriving them any other way would let the sound be placed
against a script the voice never read.

    py -3.11 scripts/gen_vo_script.py --ep PD-2026-067-ramirez
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))

from gen_narration_case import EPISODES, build_chunks  # noqa: E402


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--ep", required=True)
    ap.add_argument("--force", action="store_true", help="overwrite an existing file")
    a = ap.parse_args()

    cfg = EPISODES.get(a.ep)
    if not cfg:
        raise SystemExit(f"{a.ep} is not in the gen_narration_case registry")
    src = ROOT / "episodes" / "_planning" / cfg["planning"]
    if not src.is_file():
        raise SystemExit(f"authored script missing: {src}")

    out = ROOT / "episodes" / a.ep / "03_script" / "script.en.v001.md"
    if out.is_file() and not a.force:
        raise SystemExit(f"{out} already exists -- pass --force to replace it")

    chunks = build_chunks(a.ep, src.read_text(encoding="utf-8", errors="replace"))
    lines = [f"# {a.ep} - narration only, [VO:] form", "",
             f"Generated by scripts/gen_vo_script.py from episodes/_planning/{cfg['planning']},",
             "which is the authored document. The beats are the ones gen_narration_case actually",
             "spoke, so the sound plan is placed against the narration that exists. It carries no",
             "direction, no citation comment and no front matter.",
             "Do not edit this file. Edit the planning script and regenerate.", ""]
    lines += [f"[VO:] {c['spoken_text'].strip()}" for c in chunks if c.get("spoken_text", "").strip()]

    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {out.relative_to(ROOT)} -- {len(lines) - 7} [VO:] beat(s)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
